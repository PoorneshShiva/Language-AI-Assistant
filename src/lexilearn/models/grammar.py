from pydantic import BaseModel, Field
from typing import List, Optional, Dict

# Import specific detail models from common
from lexilearn.models.common import (
    GermanVerbsDetails,
    GermanAdjectiveDetails,
    GermanNounDetails,
    GermanConjunctionDetails,
    GermanAdverbDetails,
    GermanPrepositionDetails
)

class GermanGrammarDetails(BaseModel):
    """State to manage detailed grammar information for various parts of speech."""
    verbs_info: Optional[List[GermanVerbsDetails]] = Field(default_factory=list, 
        description="A list of detailed German verb information objects.")
    adjectives_info: Optional[List[GermanAdjectiveDetails]] = Field(default_factory=list,
        description="A list of detailed German adjective information objects.")
    nouns_info: Optional[List[GermanNounDetails]] = Field(default_factory=list, 
        description="A list of detailed German noun information objects.")
    conjunctions_info: Optional[List[GermanConjunctionDetails]] = Field(default_factory=list,
        description="A list of detailed German conjunction information objects.")
    adverbs_info: Optional[List[GermanAdverbDetails]] = Field(default_factory=list,
        description="A list of detailed German adverb information objects.")
    prepositions_info: Optional[List[GermanPrepositionDetails]] = Field(default_factory=list,
        description="A list of detailed German preposition information objects.")
    # Fields are now strongly typed using specific Pydantic models from common.py

class LanggraphGrammarNodeOutput(BaseModel):
    """
    Defines the expected output structure for a Langgraph node
    that processes or generates grammatical constructs.
    """
    processed_text: str = Field(..., description="The text processed or generated by the node.")
    analysis: Optional[Dict] = Field(None, description="Optional grammatical analysis of the text.")
